"use strict";

// Deterministic runtime catalogue. Research metrics/traces never enter the bundle.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const file = path.join(__dirname, "../lab-search-results.json");
const raw = fs.readFileSync(file, "utf8"), research = JSON.parse(raw);
if (research.quick || research.rows.length !== 1950) throw new Error("Full research matrix required");
const data = {
    schema: 1,
    source: crypto.createHash("sha256").update(raw).digest("hex"),
    plans: research.plans,
    rows: research.rows.map((r) => [r.product, r.built.length, r.qty, r.bandwidth, r.delay,
        r.winner.planId, r.winner.ticks, r.references.map((p) => p.planId)])
};
fs.writeFileSync(path.join(__dirname, "../../src/utils/labPolicyData.js"),
    "// Generated by docs/lab-search/generate-policy.cjs; do not edit.\nmodule.exports = " + JSON.stringify(data) + ";\n");
console.log("0127: exported " + data.rows.length + " cases / " + Object.keys(data.plans).length + " plans");
